APP_ROLE = os.environ.get("DB_APP_ROLE", "mailflow_app")


def _apply_security() -> None:
    """Grants, row-level security and the SECURITY DEFINER helpers.

    The application connects as APP_ROLE, which owns nothing and cannot bypass RLS. The
    migration (owner) role is not subject to the policies, which is what lets the definer
    functions below perform their narrowly scoped cross-tenant work.
    """
    op.execute(
        f"""
        DO $$
        BEGIN
          IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{APP_ROLE}') THEN
            RAISE EXCEPTION 'application role {APP_ROLE} does not exist; create it first';
          END IF;
        END $$;
        """
    )
    op.execute(f'GRANT USAGE ON SCHEMA public TO "{APP_ROLE}"')
    op.execute(f'GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO "{APP_ROLE}"')
    op.execute(f'REVOKE ALL ON alembic_version FROM "{APP_ROLE}"')
    # The audit trail is append-only for the application (UPDATE is needed to detach users).
    op.execute(f'REVOKE DELETE ON audit_events FROM "{APP_ROLE}"')

    for table in TENANT_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(
            f"""
            CREATE POLICY tenant_isolation ON {table}
            USING (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid)
            WITH CHECK (user_id = NULLIF(current_setting('app.current_user_id', true), '')::uuid)
            """
        )

    op.execute(
        """
        CREATE FUNCTION mailflow_claim_due_syncs(p_limit integer, p_lease_seconds integer)
        RETURNS TABLE (user_id uuid, account_id uuid)
        LANGUAGE sql
        SECURITY DEFINER
        SET search_path = public, pg_temp
        AS $$
          WITH missing AS (
            INSERT INTO sync_states (id, user_id, account_id, status, next_sync_at)
            SELECT gen_random_uuid(), a.user_id, a.id, 'queued',
                   now() + make_interval(secs => p_lease_seconds)
            FROM email_accounts a
            JOIN users u ON u.id = a.user_id
            WHERE a.status = 'active' AND u.status = 'active'
              AND NOT EXISTS (SELECT 1 FROM sync_states s WHERE s.account_id = a.id)
            LIMIT p_limit
            ON CONFLICT (account_id) DO NOTHING
            RETURNING sync_states.user_id, sync_states.account_id
          ), due AS (
            SELECT s.id
            FROM sync_states s
            JOIN email_accounts a ON a.id = s.account_id
            JOIN users u ON u.id = a.user_id
            WHERE a.status = 'active' AND u.status = 'active' AND s.next_sync_at <= now()
            ORDER BY s.next_sync_at
            LIMIT p_limit
            FOR UPDATE OF s SKIP LOCKED
          ), claimed AS (
            UPDATE sync_states s
            SET status = CASE WHEN s.status = 'running' THEN s.status ELSE 'queued' END,
                next_sync_at = now() + make_interval(secs => p_lease_seconds)
            FROM due
            WHERE s.id = due.id
            RETURNING s.user_id, s.account_id
          )
          SELECT m.user_id, m.account_id FROM missing m
          UNION ALL
          SELECT c.user_id, c.account_id FROM claimed c
        $$;
        """
    )
    op.execute(
        """
        CREATE FUNCTION mailflow_cleanup_expired() RETURNS void
        LANGUAGE sql
        SECURITY DEFINER
        SET search_path = public, pg_temp
        AS $$
          DELETE FROM user_sessions
            WHERE expires_at < now() - interval '7 days'
               OR revoked_at < now() - interval '7 days';
          DELETE FROM email_verification_tokens WHERE expires_at < now() - interval '1 day';
          DELETE FROM password_reset_tokens WHERE expires_at < now() - interval '1 day';
          DELETE FROM oauth_states WHERE expires_at < now() - interval '1 hour';
          DELETE FROM audit_events WHERE created_at < now() - interval '180 days';
        $$;
        """
    )
    for signature in ("mailflow_claim_due_syncs(integer, integer)", "mailflow_cleanup_expired()"):
        op.execute(f"REVOKE ALL ON FUNCTION {signature} FROM PUBLIC")
        op.execute(f'GRANT EXECUTE ON FUNCTION {signature} TO "{APP_ROLE}"')
